"""Serve the real FlyWire neuropil surface transformed from FAFB14.

navis-flybrains documents FLYWIRE.mesh as FAFB14 neuropil geometry
registered into FlyWire space. Distinct from FLYWIRE.mesh_whole_brain,
which is a processed FAFB *tissue mask*. We expose them separately.
Original triangles are served unchanged and verified against a pinned
public Git blob, not generated by a decorative renderer.
"""

from __future__ import annotations

import hashlib
import urllib.error
from functools import lru_cache
from urllib.request import Request, urlopen

from app.data.tissue import PINNED_SOURCE_COMMIT, MAX_BYTES

NEUROPIL_GIT_BLOB_SHA1 = "468c217c41602a8d34df2af6afd00a2aa1c11077"
NEUROPIL_UPSTREAM_URL = (
    "https://raw.githubusercontent.com/navis-org/navis-flybrains/"
    + PINNED_SOURCE_COMMIT + "/flybrains/meshes/FLYWIRE.ply"
)
NEUROPIL_PROVENANCE_URL = (
    "https://github.com/navis-org/navis-flybrains/blob/"
    + PINNED_SOURCE_COMMIT + "/flybrains/templates.py"
)


class NeuropilMeshUnavailable(RuntimeError):
    """No original, authenticated FAFB-aligned neuropil bytes are available."""


@lru_cache(maxsize=1)
def load_official_neuropil_mesh() -> tuple[bytes, str]:
    """Fetch one pinned source, checking Git blob content byte for byte."""
    request = Request(
        NEUROPIL_UPSTREAM_URL,
        headers={"User-Agent": "Neuroverse-scientific-education/0.3"},
    )
    try:
        with urlopen(request, timeout=18) as response:
            length = response.headers.get("Content-Length")
            if length and int(length) > MAX_BYTES:
                raise NeuropilMeshUnavailable("Official neuropil PLY exceeds size limit")
            raw = response.read(MAX_BYTES + 1)
    except (urllib.error.URLError, TimeoutError, OSError) as error:
        raise NeuropilMeshUnavailable("Official FlyWire neuropil mesh unavailable") from error
    if len(raw) < 100 or len(raw) > MAX_BYTES or not raw.startswith(b"ply"):
        raise NeuropilMeshUnavailable("Official neuropil data are not a valid-size PLY")
    git_sha = hashlib.sha1(
        f"blob {len(raw)}\0".encode("ascii") + raw, usedforsecurity=False
    ).hexdigest()
    if git_sha != NEUROPIL_GIT_BLOB_SHA1:
        raise NeuropilMeshUnavailable("Original neuropil Git blob SHA-1 mismatch")
    return raw, hashlib.sha256(raw).hexdigest()
